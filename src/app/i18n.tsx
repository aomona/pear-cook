const messagesByLocale: Record<Locale, Messages> = { ja, en };
const STORAGE_KEY = "pear-cook.locale";

function initialLocale(): Locale {
  const stored = getSafeStorageItem(STORAGE_KEY);
  if (stored === "ja" || stored === "en") return stored;
  return window.navigator.language.toLowerCase().startsWith("ja") ? "ja" : "en";
}

export function formatMessage(template: string, variables: Variables = {}): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(variables[key] ?? `{${key}}`));
}

type I18nContextValue = {
  locale: Locale;
  messages: Messages;
  setLocale: (locale: Locale) => void;
  format: (template: string, variables?: Variables) => string;
  formatDate: (value: string | number | Date) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(initialLocale);

  useEffect(() => {
    document.documentElement.lang = locale;
    setSafeStorageItem(STORAGE_KEY, locale);
  }, [locale]);

  const value = useMemo<I18nContextValue>(() => ({
    locale,
    messages: messagesByLocale[locale],
    setLocale: setLocaleState,
    format: formatMessage,
    formatDate: (input) => new Intl.DateTimeFormat(locale === "ja" ? "ja-JP" : "en-US").format(new Date(input)),
  }), [locale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside I18nProvider");
  return value;
}
